//! Compile every sensor and generate the embedded artifact table.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    for sensor in bpf_build::SENSORS {
        println!("cargo:rerun-if-changed=../../bpf/sensors/{sensor}.bpf.c");
    }
    println!("cargo:rerun-if-changed=../../bpf/include/event_abi.h");
    println!("cargo:rerun-if-changed=../bpf-build/src/lib.rs");
    println!("cargo:rerun-if-changed=build.rs");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let artifacts = match bpf_build::build() {
        Ok(artifacts) => artifacts,
        Err(error) => {
            panic!("cannot build the BPF sensors: {error}");
        }
    };

    let mut generated = String::new();
    generated.push_str("// Generated by bpf-loader/build.rs. Do not edit.\n");
    generated.push_str("pub static SENSORS: &[EmbeddedSensor] = &[\n");
    for artifact in &artifacts {
        let bytes_path = artifact
            .object
            .canonicalize()
            .unwrap_or_else(|_| artifact.object.clone());
        writeln!(
            generated,
            "    EmbeddedSensor {{ name: \"{}\", arch: \"{}\", sha256: \"{}\", bytes: include_bytes!(\"{}\") }},",
            artifact.sensor,
            artifact.arch,
            artifact.sha256,
            escape_path(&bytes_path)
        )
        .expect("write generated table");
    }
    generated.push_str("];\n");

    let generated_path = out_dir.join("embedded_artifacts.rs");
    fs::write(&generated_path, generated).expect("write generated table");
    println!(
        "cargo:rustc-env=EBPF_EMBEDDED_ARTIFACTS={}",
        generated_path.display()
    );
}

fn escape_path(path: &Path) -> String {
    path.display()
        .to_string()
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
}
